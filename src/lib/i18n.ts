export function isUiLanguage(value: string | null | undefined): value is UiLanguage {
  return LANGUAGES.some((language) => language.id === value)
}

export function t(language: string | null | undefined, key: CopyKey): string {
  const id = isUiLanguage(language) ? language : 'en'
  return DICTS[id][key] ?? EN[key]
}
